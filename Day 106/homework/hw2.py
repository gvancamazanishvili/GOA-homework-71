# 2) რა დანიშნულება აქვს finally, else და raise keyword-ებს?

# finally -  Error-ია თუ კოდუ თავისუფლად გაეშვება finnaly keyword-ით ჩვენ შეგვიძლია ნებისმიერი ტიპის ტექსტი გავუშვათ ტერმინალში


# else: - ჩვენ შეგვიძლია else keyword-ის დახმარებით გამოვიტანოთ მესიჯი მხოლოდ იმ შემთხვევაში როდესაც error-ის არ არის კოდში 

# raise -  ჩვენ შეგვიძლია ტერმინალში გამოვიწვიოთ იმ სახის Error-ი რომელიც შეიძლება დაგვეშვა კოდში ამის შემდეგ ჩვენ () - სახით შეგვიძლია დავწეროთ მესიჯი თუ რა Error-ი გვქონდა კოდში 
