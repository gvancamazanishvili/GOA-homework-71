# 1) კომენტარის სახით ახსენით რას აკეთებს len(), append(), insert() და pop() ფუნქციები


# len() -განსაზღვრავს list-ის სიგრძეს

# append() - გამოიზახება დოტნოტაციით და მისი ფუნქცია გულისხმობს სიიის ბოლოში სიტყვის ან რიცხვის დამატებას

# insert() - ფუნქციას გააჩნია ორი არგუმენტი. პირველი არის ის ინდექსი რომლის ადგილასაც გვინდა დამატება და მეორე თუ რითი გვინდა შეცვლა. გამოიძახება დოტნოტაციით

# pop() - ამ ფუნქციის საშვალებით ჩვენ შეგვიძლია რომელიმე წევრის ამოგდება სიიდან