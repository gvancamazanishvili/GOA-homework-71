# 3) ჩამოწერეთ რამდენი ტიპის ფუქნცია არსებობს პითონში?
# თითოეულს მიუწერეთ მოკლე დახასიათება.


# სულ არსებობს სამი სახის ფუნქცია: pure, impure, high-order function

#  pure functions - ისეთი ფუნქცია რომლის მოქმედება მხოლოდ შიგნითვე ფუნქციაში ხდება და მისი output-ი არის იგივე რას input-ი 

# impure function - ისეთი ფუნცია რომელიიც დამოკიდებულია ფუნქციის გარეთ არსებულ მექანიკაზე (მაგ:list, variables) 

# high-order function - ფუნქცია რომელიც იყენებს სხვა ფუნქციას მის არგუმენტად 